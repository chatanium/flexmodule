#!/usr/bin/env python3
"""Generate the host-only static dispatch to P2's reviewed event projectors."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[2]
rows = json.loads((root / 'tools/protocol/event-mapping.json').read_text())['events']
out = ['// Code generated by tools/protocol/generate-backend-events.py; DO NOT EDIT.', 'package discordbackend', '', 'import (', '"context"', '"github.com/chatanium/discordgo"', 'core "github.com/thirdscam/chatanium-flexmodule/shared/core-v2"', 'discordv2 "github.com/thirdscam/chatanium-flexmodule/shared/discord-v2"', '"google.golang.org/protobuf/proto"', ')', '', 'func projectGatewayEvent(ctx context.Context, name string, raw []byte, source any, encoder core.CredentialEncoder, policy discordv2.ProjectionPolicy)(proto.Message,error){', 'switch name {']
for row in rows:
    if not row['moduleFacing']:
        continue
    typ = row['sourceType']
    out.extend([f'case "{row["canonicalName"]}":', f'value,ok:=source.(*discordgo.{typ});if !ok||value==nil{{return nil,invalid("DISCORD_EVENT_TYPE_INVALID")}}', f'return discordv2.Project{row["projection"]}(ctx,raw,value,encoder,policy)'])
out.extend(['default:return nil,invalid("DISCORD_EVENT_NOT_REGISTERED")', '}', '}', ''])
(root / 'internal/backend/discord/events_generated.go').write_text('\n'.join(out))
