#!/usr/bin/env python3
"""Emit the complete typed module client from P1 contracts and P2 public views.

This generates source and a coverage catalog, not evidence of exercised RPCs.
No protobuf generation, formatting, network access or validation commands run.
"""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MAPPING = ROOT / "tools/protocol/api-mapping.json"
P2 = ROOT / "shared/discord-v2/conversions_generated.go"
HEADER = '// Code generated by tools/protocol/generate-client.py; DO NOT EDIT.\n\npackage discordv2\n\n'
IMPORTS = '''import (
    "context"
    "strconv"
    "time"

    "github.com/chatanium/discordgo"
    corewire "github.com/thirdscam/chatanium-flexmodule/proto/core-v2"
    wire "github.com/thirdscam/chatanium-flexmodule/proto/discord-v2"
    core "github.com/thirdscam/chatanium-flexmodule/shared/core-v2"
)

'''


def declarations(text):
    pending, result = [], []
    for part in text.split(','):
        words = part.split()
        if len(words) == 1:
            pending.append(words[0])
        elif len(words) == 2:
            name, typ = words
            result.extend((n, typ) for n in pending + [name])
            pending = []
        elif words:
            raise ValueError(part)
    if pending:
        raise ValueError(pending)
    return result


def signature_args(signature):
    return declarations(re.fullmatch(r'func \(s \*Session\) \w+\(([^)]*)\) .+', signature)[1])


def go_field(name):
    # protoc's Go field convention, not SDK acronym conventions.
    return ''.join(word[0].upper() + word[1:] for word in name.split('_'))


def generate():
    mapping = json.loads(MAPPING.read_text())
    operations = {op['name']: op for op in mapping['operations']}
    wrappers = {w['name']: w for w in mapping['collectionWrappers']}
    aliases = [a for a in mapping['sourceClassifications'] if a['classification'] == 'convenience_alias']
    # Converter declarations are P2's authoritative public input/output types.
    # P2 emits unformatted Go; discovery must not depend on a prior gofmt pass.
    converter_declaration = re.compile(
        r'\bfunc\s+(\w+)ToProto\s*\(\s*src\s+'
        r'(\*\w+(?:\.\w+)?)\s*\)\s*'
        r'\(\s*\*wire\.(\w+)\s*,\s*error\s*\)'
    )
    safe = {
        wire_type: source_type
        for _, source_type, wire_type in converter_declaration.findall(P2.read_text())
    }
    safe.update(Interaction='*InteractionHandle', Webhook='*WebhookHandle')
    scalar = {'string', 'bool', 'int', 'int64', 'uint32', 'uint64'}

    def go_type(typ):
        if typ.startswith('[]'):
            return '[]' + go_type(typ[2:])
        if typ.startswith('map[string]'):
            return 'map[string]' + go_type(typ[11:])
        if typ == 'io.Reader':
            return '*corewire.UploadedFileRef'
        if typ.startswith('*'):
            raw = typ[1:]
            if raw in safe:
                return safe[raw]
            return '*' + go_type(raw)
        if typ in scalar or typ.startswith('time.'):
            return typ
        if typ in safe:
            return safe[typ].removeprefix('*')
        return 'discordgo.' + typ

    def result_type(op):
        if op['response'] == 'google.protobuf.Empty':
            return None
        if op['name'] == 'GatewayBot':
            return '*discordgo.GatewayBotResponse'
        return go_type(op['responseFields'][0]['sourceType'])

    def result_signature(typ):
        return 'error' if typ is None else '(' + typ + ', error)'

    def zero(typ):
        if typ is None:
            return ''
        if typ.startswith(('*', '[]', 'map[')):
            return 'nil'
        if typ == 'string':
            return '""'
        if typ == 'bool':
            return 'false'
        return '0'

    def failure(typ, error):
        return 'return ' + (zero(typ) + ', ' if typ else '') + error

    output = [HEADER, IMPORTS]
    coverage = []
    # Recursively emit static collection and domain conversions. No reflection,
    # JSON roundtrip, SDK REST transport or generic raw RPC is involved.
    def to_wire(field, expr, target, lines, fail, depth=0):
        typ = field['type']
        source = field.get('sourceType', '')
        if typ in wrappers:
            w = wrappers[typ]
            elem_source = source[2:] if w['kind'] == 'list' else source[11:]
            container = '[]' + wire_go_type(w['element']) if w['kind'] == 'list' else 'map[string]' + wire_go_type(w['element'])
            lines.append(f'if {expr} != nil {{')
            lines.append(f'{target} = &wire.{typ}{{Values: make({container}, len({expr}))}}')
            key, item = 'index' + str(depth), 'item' + str(depth)
            lines.append(f'for {key}, {item} := range {expr} {{')
            to_wire({'type': w['element'], 'sourceType': elem_source}, item, f'{target}.Values[{key}]', lines, fail, depth+1)
            lines.extend(['}', '}'])
        elif typ == 'flexmodule.core.v2.CredentialRef':
            lines.extend([f'if {expr} == nil {{ {fail("clientInvalid()")} }}', f'if err := validateCredentialRef({expr}, newConversion("StructToProto", "CredentialRef"), ""); err != nil {{ {fail("err")} }}', f'{target} = cloneCredential({expr})'])
        elif typ == 'google.protobuf.Timestamp':
            lines.extend([f'if {expr} != nil {{', f'converted, err := timestampToProto(*{expr}, newConversion("StructToProto", "Timestamp"), "")', f'if err != nil {{ {fail("err")} }}', f'{target} = converted', '}'])
        elif typ in safe:
            pointer = expr if source.startswith('*') else '&' + expr
            lines.append(f'if {pointer} == nil {{ {fail("clientInvalid()")} }}' if source.startswith('*') else '// Convert the value without changing the caller\'s input.')
            converter = typ + ('Handle' if typ in {'Webhook', 'Interaction'} else '') + 'ToProto'
            # Block scope keeps every converted/err declaration local.
            lines.extend(['{', f'converted, err := {converter}({pointer})', f'if err != nil {{ {fail("err")} }}', f'{target} = converted', '}'])
        elif field.get('optional'):
            lines.append(f'{target} = copyPointer({expr})')
        elif typ == 'string' and source == 'int64':
            lines.extend([f'if {expr} < 0 {{ {fail("clientInvalid()")} }}', f'{target} = strconv.FormatInt({expr}, 10)'])
        elif typ == 'sint64':
            lines.append(f'{target} = int64({expr})')
        elif typ in {'string', 'bool', 'uint32', 'uint64'}:
            lines.append(f'{target} = {expr}')
        else:
            raise ValueError(('unsupported input', field))

    def wire_go_type(typ):
        if typ == 'sint64':
            return 'int64'
        if typ in {'string', 'bool', 'uint32', 'uint64'}:
            return typ
        return '*wire.' + typ

    def from_wire(field, expr, target, lines, fail, depth=0):
        typ, source = field['type'], field['sourceType']
        if typ in wrappers:
            w = wrappers[typ]
            lines.append(f'if {expr} == nil {{ {fail("clientMissing()")} }}')
            lines.append(f'{target} = make({go_type(source)}, len({expr}.Values))')
            key, item = 'index' + str(depth), 'item' + str(depth)
            lines.append(f'for {key}, {item} := range {expr}.Values {{')
            elem_source = source[2:] if w['kind'] == 'list' else source[11:]
            from_wire({'type': w['element'], 'sourceType': elem_source}, item, f'{target}[{key}]', lines, fail, depth+1)
            lines.append('}')
        elif typ in safe:
            lines.append(f'if {expr} == nil {{ {fail("clientMissing()")} }}')
            converter = 'ProtoTo' + typ + ('Handle' if typ in {'Webhook', 'Interaction'} else '')
            lines.extend(['{', f'converted, err := {converter}({expr})', f'if err != nil {{ {fail("err")} }}', f'{target} = converted', '}'])
        elif typ == 'string' and source == 'int64':
            lines.extend(['{', f'converted, err := parsePermissions({expr})', f'if err != nil {{ {fail("clientMissing()")} }}', f'{target} = converted', '}'])
        elif typ in {'string', 'bool', 'uint32', 'uint64'}:
            lines.append(f'{target} = {expr}')
        else:
            raise ValueError(('unsupported output', field))

    for name, op in operations.items():
        typ = result_type(op)
        fail = lambda error: failure(typ, error)
        params = []
        fields = [f for f in op['requestFields'] if f['name'] != 'options' and not (name == 'Guild' and f['name'] == 'with_counts')]
        for f in fields:
            arg = 'credential' if f['name'] == 'credential' else f['sourceName']
            arg_type = '*corewire.CredentialRef' if f['name'] == 'credential' else '*string' if f['name'] == 'reason' else go_type(f['sourceType'])
            params.append(arg + ' ' + arg_type)
        method_name = 'guild' if name == 'Guild' else name
        signature_params = ['ctx context.Context'] + params + (['withCounts bool'] if name == 'Guild' else []) + ['options ...RequestOption']
        signature = f'func (c *Client) {method_name}(' + ', '.join(signature_params) + ') ' + result_signature(typ)
        lines = [signature + ' {', f'if err := clientContext(ctx); err != nil {{ {fail("err")} }}', f'request := &wire.{op["request"]}{{Options: clientOptions(options)}}']
        if name == 'UpdateStatusComplex':
            lines.append('if usd.Activities == nil { usd.Activities = []*discordgo.Activity{} }')
        for f in fields:
            arg = 'credential' if f['name'] == 'credential' else f['sourceName']
            to_wire(f, arg, 'request.' + go_field(f['name']), lines, fail)
        if name == 'Guild':
            lines.append('request.WithCounts = withCounts')
        if any(f['name'] == 'reason' for f in fields):
            lines.append(f'if request.Reason != nil && request.Options != nil && request.Options.AuditLogReason != nil && *request.Reason != *request.Options.AuditLogReason {{ {fail("clientInvalid()")} }}')
        # Required empty responses are checked too; nil,nil is never success.
        lines.extend([f'response, err := c.helper.{name}(core.HelperContext(ctx), request)', f'if err != nil {{ {fail("err")} }}', f'if response == nil {{ {fail("clientMissing()")} }}'])
        if typ is None:
            lines.append('return nil')
        else:
            if name == 'WebhookThreadExecute':
                lines.append('if response.Value == nil && !wait { return nil, nil }')
            lines.append('var result ' + typ)
            field = {'type': 'GatewayBotResponse', 'sourceType': '*GatewayBotResponse'} if name == 'GatewayBot' else op['responseFields'][0]
            from_wire(field, 'response' if name == 'GatewayBot' else 'response.Value', 'result', lines, fail)
            lines.append('return result, nil')
        lines.extend(['}', ''])
        if name == 'Guild':
            public = 'func (c *Client) Guild(ctx context.Context, guildID string, options ...RequestOption) (*discordgo.Guild, error)'
            output.append('// Guild retrieves the snapshot without requesting approximate counts.\n' + public + ' {\nreturn c.guild(ctx, guildID, false, options...)\n}\n\n')
            public_signature = public
        else:
            public_signature = signature
        output.append('// ' + name + ' invokes ' + op['capability'] + '.\n')
        if name == 'GuildTemplateCreate':
            output.append('// Unlike the source SDK, failures are always returned to the caller.\n')
        if name == 'WebhookDeleteWithToken':
            output.append('// Discord returns no body; the convenience result is error-only.\n')
        if name in {'GuildBanCreateWithReason', 'GuildMemberDeleteWithReason'}:
            output.append('// A nil reason is absent; a pointer to an empty string is explicit empty.\n')
        output.append('\n'.join(lines) + '\n')
        coverage.append({'name': name, 'kind': 'canonical', 'signature': public_signature, 'fullMethod': op['fullMethod'], 'request': op['request'], 'response': op['response'], 'inputFields': [f['name'] for f in op['requestFields']], 'output': typ or 'error', 'source': op['source']})

    # Aliases use reviewed explicit recipes rather than guessing endpoint rules.
    alias_output = [HEADER, '''import (
    "context"
    "time"

    "github.com/chatanium/discordgo"
    corewire "github.com/thirdscam/chatanium-flexmodule/proto/core-v2"
)

''']
    for alias in aliases:
        name, canonical = alias['name'], alias['protoOperation']
        args = [(n, t) for n, t in signature_args(alias['sourceSignature']) if t != '...RequestOption']
        params = [(('credential' if n == 'token' else n), ('*corewire.CredentialRef' if n == 'token' else go_type(t))) for n, t in args]
        # Member mutation aliases intentionally retain their source error-only API.
        error_only = name in {'GuildMemberDeafen', 'GuildMemberDelete', 'GuildMemberMove', 'GuildMemberMute', 'GuildMemberTimeout', 'GuildBanCreate', 'InteractionResponseDelete', 'FollowupMessageDelete', 'RequestGuildMembersBatch', 'RequestGuildMembersBatchList', 'UpdateCustomStatus', 'UpdateGameStatus', 'UpdateListeningStatus', 'UpdateStreamingStatus', 'UpdateWatchStatus'}
        typ = None if error_only else result_type(operations[canonical])
        fail = lambda error: failure(typ, error)
        signature = f'func (c *Client) {name}(' + ', '.join(['ctx context.Context'] + [n + ' ' + t for n, t in params] + ['options ...RequestOption']) + ') ' + result_signature(typ)
        lines = [signature + ' {']
        call = None
        if name in {'ChannelEditComplex', 'GuildMemberEditComplex'}:
            call = f'c.{canonical}(ctx, ' + ', '.join(n for n, _ in params) + ', options...)'
        elif name == 'GuildWithCounts':
            call = 'c.guild(ctx, guildID, true, options...)'
        elif name == 'GuildBanCreate':
            call = 'c.GuildBanCreateWithReason(ctx, guildID, userID, nil, days, options...)'
        elif name == 'GuildMemberDelete':
            call = 'c.GuildMemberDeleteWithReason(ctx, guildID, userID, nil, options...)'
        elif name in {'GuildMemberMove', 'GuildMemberMute', 'GuildMemberDeafen', 'GuildMemberTimeout'}:
            if name in {'GuildMemberMove', 'GuildMemberTimeout'}:
                arg, value_type, field = ('channelID', 'string', 'ChannelID') if name == 'GuildMemberMove' else ('until', 'time.Time', 'CommunicationDisabledUntil')
                lines.extend([f'value := &Nullable[{value_type}]{{Null: {arg} == nil}}', f'if {arg} != nil {{ value.Value = *{arg} }}'])
                patch = f'&GuildMemberParamsView{{{field}: value}}'
            else:
                arg, field = ('mute', 'Mute') if name == 'GuildMemberMute' else ('deaf', 'Deaf')
                patch = f'&GuildMemberParamsView{{{field}: &{arg}}}'
            lines.extend([f'_, err := c.GuildMemberEdit(ctx, guildID, userID, {patch}, options...)', 'return err'])
        elif name == 'GuildChannelCreate':
            call = 'c.GuildChannelCreateComplex(ctx, guildID, discordgo.GuildChannelCreateData{Name: name, Type: ctype}, options...)'
        elif canonical == 'ChannelMessageSendComplex':
            names = {n for n, _ in params}
            data = []
            if 'content' in names:
                data.append('Content: content')
            if name == 'ChannelMessageSendTTS':
                data.append('TTS: true')
            if 'embed' in names:
                data.append('Embeds: []*discordgo.MessageEmbed{embed}')
            if 'embeds' in names:
                data.append('Embeds: embeds')
            if 'reference' in names:
                lines.append(f'if reference == nil {{ {fail("clientInvalid()")} }}')
                data.append('Reference: reference')
            if 'r' in names:
                data.append('Files: []FileAttachment{{Ref: r, Filename: name}}')
            call = 'c.ChannelMessageSendComplex(ctx, channelID, &MessageSendView{' + ', '.join(data) + '}, options...)'
        elif canonical == 'ChannelMessageEditComplex':
            if name == 'ChannelMessageEdit':
                patch = 'Content: &content'
            else:
                if name == 'ChannelMessageEditEmbed':
                    lines.append('embeds := []*discordgo.MessageEmbed{embed}')
                patch = 'Embeds: &embeds'
            call = 'c.ChannelMessageEditComplex(ctx, &MessageEditPatch{ID: messageID, ChannelID: channelID, ' + patch + '}, options...)'
        elif name in {'Invite', 'InviteWithCounts'}:
            call = f'c.InviteComplex(ctx, inviteID, "", /* withCounts */ {str(name == "InviteWithCounts").lower()}, /* withExpiration */ false, options...)'
        elif name == 'WebhookExecute':
            call = 'c.WebhookThreadExecute(ctx, webhookID, credential, wait, "", data, options...)'
        elif name in {'MessageThreadStart', 'ThreadStart'}:
            if name == 'MessageThreadStart':
                call = 'c.MessageThreadStartComplex(ctx, channelID, messageID, &discordgo.ThreadStart{Name: name, AutoArchiveDuration: archiveDuration}, options...)'
            else:
                call = 'c.ThreadStartComplex(ctx, channelID, &discordgo.ThreadStart{Name: name, Type: typ, AutoArchiveDuration: archiveDuration}, options...)'
        elif canonical == 'ForumThreadStartComplex':
            message = 'Content: content' if name == 'ForumThreadStart' else 'Embeds: []*discordgo.MessageEmbed{embed}' if name == 'ForumThreadStartEmbed' else 'Embeds: embeds'
            call = 'c.ForumThreadStartComplex(ctx, channelID, &discordgo.ThreadStart{Name: name, AutoArchiveDuration: archiveDuration}, &MessageSendView{' + message + '}, options...)'
        elif name.startswith(('InteractionResponse', 'FollowupMessage')):
            lines.extend(['webhookID, credential, err := interactionWebhookTarget(interaction)', f'if err != nil {{ {fail("err")} }}'])
            message = '"@original"' if name.startswith('InteractionResponse') else 'messageID'
            if canonical == 'WebhookMessage':
                call = f'c.WebhookMessage(ctx, webhookID, credential, {message}, options...)'
            elif canonical == 'WebhookMessageEdit':
                call = f'c.WebhookMessageEdit(ctx, webhookID, credential, {message}, ' + ('newresp' if name == 'InteractionResponseEdit' else 'data') + ', options...)'
            elif canonical == 'WebhookMessageDelete':
                call = f'c.WebhookMessageDelete(ctx, webhookID, credential, {message}, options...)'
            else:
                call = 'c.WebhookThreadExecute(ctx, webhookID, credential, wait, "", data, options...)'
        elif canonical == 'UpdateStatusComplex':
            lines.append('status := discordgo.UpdateStatusData{Status: "online", Activities: []*discordgo.Activity{}}')
            if name in {'UpdateGameStatus', 'UpdateWatchStatus', 'UpdateStreamingStatus'}:
                lines.append('if idle > 0 { status.IdleSince = &idle }')
            condition = 'state' if name == 'UpdateCustomStatus' else 'name'
            kind = {'UpdateGameStatus': 'discordgo.ActivityTypeGame', 'UpdateWatchStatus': 'discordgo.ActivityTypeWatching', 'UpdateStreamingStatus': 'discordgo.ActivityTypeGame', 'UpdateListeningStatus': 'discordgo.ActivityTypeListening', 'UpdateCustomStatus': 'discordgo.ActivityTypeCustom'}[name]
            activity_name = '"Custom Status"' if name == 'UpdateCustomStatus' else 'name'
            lines.extend([f'if {condition} != "" {{', f'activity := &discordgo.Activity{{Name: {activity_name}, Type: {kind}}}'])
            if name == 'UpdateCustomStatus':
                lines.append('activity.State = state')
            if name == 'UpdateStreamingStatus':
                lines.append('if url != "" { activity.Type = discordgo.ActivityTypeStreaming; activity.URL = url }')
            lines.extend(['status.Activities = append(status.Activities, activity)', '}'])
            call = 'c.UpdateStatusComplex(ctx, status, options...)'
        elif name in {'RequestGuildMembersBatch', 'RequestGuildMembersBatchList'}:
            lines.extend(['if err := clientContext(ctx); err != nil { return err }', 'for _, guildID := range guildIDs {', 'if err := clientContext(ctx); err != nil { return err }'])
            query = 'query' if name == 'RequestGuildMembersBatch' else 'userIDs'
            lines.extend([f'if err := c.{canonical}(ctx, guildID, {query}, limit, nonce, presences, options...); err != nil {{ return err }}', '}', 'return nil'])
        else:
            raise ValueError(('missing alias implementation', name))
        if call:
            lines.append('return ' + call)
        lines.extend(['}', ''])
        alias_output.append('// ' + name + ' maps explicitly to ' + canonical + '.\n')
        if name.startswith('RequestGuildMembersBatch'):
            alias_output.append('// Calls are sequential in input order, stop on the first error/cancellation,\n// and never roll back earlier writes or retry the batch. An empty input sends nothing.\n')
        alias_output.append('\n'.join(lines) + '\n')
        coverage.append({'name': name, 'kind': 'alias', 'signature': signature, 'canonical': canonical, 'mapping': alias['mapping']})

    ownership_signatures = {
        'RegisterInteractionRoutes': 'func (c *Client) RegisterInteractionRoutes(ctx context.Context, claims []*wire.InteractionRouteClaim) error',
        'UnregisterInteractionRoutes': 'func (c *Client) UnregisterInteractionRoutes(ctx context.Context, claims []*wire.InteractionRouteClaim) error',
        'GetProvisionedCredentialRef': 'func (c *Client) GetProvisionedCredentialRef(ctx context.Context, bindingName string) (*corewire.CredentialRef, error)',
    }
    coverage.extend({'name': op['name'], 'kind': 'ownership', 'fullMethod': op['fullMethod'], 'signature': ownership_signatures[op['name']]} for op in mapping['ownershipOperations'])
    catalog = {'generator': 'python3 tools/protocol/generate-client.py', 'inputSHA256': {'api-mapping.json': hashlib.sha256(MAPPING.read_bytes()).hexdigest(), 'conversions_generated.go': hashlib.sha256(P2.read_bytes()).hexdigest()}, 'counts': {'canonical': len(operations), 'aliases': len(aliases), 'ownership': len(mapping['ownershipOperations'])}, 'evidence': 'Source implementation coverage only; no claim of compiled, tested or exercised backend behavior.', 'methods': coverage}
    outputs = {'shared/discord-v2/client_generated.go': ''.join(output), 'shared/discord-v2/aliases.go': ''.join(alias_output), 'tools/protocol/client-coverage.json': json.dumps(catalog, ensure_ascii=False, indent=2) + '\n'}
    for name, content in outputs.items():
        (ROOT / name).write_text(content)
        print('Wrote ' + name)


if __name__ == '__main__':
    generate()
